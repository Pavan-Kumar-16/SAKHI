import { callGemini } from "./gemini";
import { buildSakhiPrompt } from "./sakhiPrompt";

import type {
  ChatMessage,
  MessageAnalysis,
  VerifiedVerse,
} from "@/types/chat";

interface GenerateResponseParams {
  userMessage: string;
  analysis: MessageAnalysis;
  verse: VerifiedVerse | null;
  conversationHistory: ChatMessage[];
  userName?: string;
  language?: string;
  currentMood?: string;
}

interface GeminiResponse {
  reply: string;
}

export async function generateResponse({
  userMessage,
  analysis,
  verse,
  conversationHistory,
  userName,
  language,
}: GenerateResponseParams): Promise<string> {
  const prompt = buildSakhiPrompt({
    userMessage,
    analysis,
    verse,
    conversationHistory,
    userName,
    language,
  });

  try {
    const result = await callGemini(prompt, {
      temperature: 0.7,
    });

    const parsed = JSON.parse(result) as GeminiResponse;

    if (!parsed.reply || typeof parsed.reply !== "string") {
      throw new Error("Invalid response generated by Gemini");
    }

    return parsed.reply.trim();
  } catch (error) {
    console.error("Response generation failed:", error);

    if (analysis.needsMoreContext) {
      return userName
        ? `I'm listening, ${userName}. Can you tell me a little more about what's been happening?`
        : "I'm listening. Can you tell me a little more about what's been happening?";
    }

    return "I'm here with you. Tell me a little more about what's on your mind.";
  }
}